# Builds face-geometry.js from MediaPipe canonical_face_model.obj (Apache-2.0).
import numpy as np, json
V=[];F=[]
for l in open('canonical_face_model.obj'):
    p=l.split()
    if not p: continue
    if p[0]=='v': V.append(list(map(float,p[1:4])))
    if p[0]=='f': F.append([int(t.split('/')[0])-1 for t in p[1:4]])
V=np.array(V);F=np.array(F)
X0,X1,Y0,Y1,S=-8.0,8.0,-9.6,8.6,0.25
nx=int(round((X1-X0)/S))+1; ny=int(round((Y1-Y0)/S))+1
Z=np.full((ny,nx),np.nan)
for f in F:
    a,b,c=V[f]
    xmin,xmax=min(a[0],b[0],c[0]),max(a[0],b[0],c[0]); ymin,ymax=min(a[1],b[1],c[1]),max(a[1],b[1],c[1])
    for j in range(int(np.floor((ymin-Y0)/S)),int(np.ceil((ymax-Y0)/S))+1):
        for i in range(int(np.floor((xmin-X0)/S)),int(np.ceil((xmax-X0)/S))+1):
            if not(0<=i<nx and 0<=j<ny): continue
            px,py=X0+i*S,Y0+j*S
            d=(b[1]-c[1])*(a[0]-c[0])+(c[0]-b[0])*(a[1]-c[1])
            if abs(d)<1e-9: continue
            w1=((b[1]-c[1])*(px-c[0])+(c[0]-b[0])*(py-c[1]))/d
            w2=((c[1]-a[1])*(px-c[0])+(a[0]-c[0])*(py-c[1]))/d
            w3=1-w1-w2
            if min(w1,w2,w3)<-1e-6: continue
            z=w1*a[2]+w2*b[2]+w3*c[2]
            if np.isnan(Z[j,i]) or z>Z[j,i]: Z[j,i]=z
flat=[(-99 if np.isnan(v) else round(float(v),2)) for v in Z.flatten()]
loops={
 'lipsOuter':[61,185,40,39,37,0,267,269,270,409,291,375,321,405,314,17,84,181,91,146],
 'lipsInner':[78,191,80,81,82,13,312,311,310,415,308,324,318,402,317,14,87,178,88,95],
 'eyeA':[33,246,161,160,159,158,157,173,133,155,154,153,145,144,163,7],
 'eyeB':[263,466,388,387,386,385,384,398,362,382,381,380,374,373,390,249],
 'browA':[70,63,105,66,107],'browB':[300,293,334,296,336],
 'oval':[10,338,297,332,284,251,389,356,454,323,361,288,397,365,379,378,400,377,152,148,176,149,150,136,172,58,132,93,234,127,162,21,54,103,67,109],
 'noseBridge':[168,6,197,195,5,4,1],'noseBase':[98,97,2,326,327],
}
out={'grid':{'x0':X0,'y0':Y0,'step':S,'nx':nx,'ny':ny,'z':flat},
     'loops':{k:[[round(float(c),3) for c in V[i]] for i in v] for k,v in loops.items()}}
open('/workspace/jarvis-grafik/avatar-live/face-geometry.js','w').write(
 '/* Face depth field + feature loops derived from MediaPipe canonical_face_model.obj\n * (c) Google LLC, Apache License 2.0. Units: cm, y up, z towards viewer. Generated by tools/export_face.py */\n'
 'window.JARVIS_FACE_GEOMETRY='+json.dumps(out,separators=(',',':'))+';\n')
print(nx,ny,np.isnan(Z).sum())
