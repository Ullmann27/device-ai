/**
 * Offline, image-based avatar animation LAB. It intentionally does not claim a 3D rig:
 * no mesh, GPU shader, or ARKit phoneme/viseme tracks are generated by this activity.
 *
 * The original Continuum orb is still the primary brand / home-screen experience.
 * This activity imports a user-owned portrait and tests TTS-linked mouth motion safely
 * without paid services, app-private model data changes or background work.
 */
class ContinuumAvatarLabActivity : Activity() {
    companion object {
        private const val PICK_PORTRAIT = 28041
        private const val PREFS = "continuum_avatar_lab_v1"
        private const val PORTRAIT_URI = "portrait_uri"
        private const val MAX_IMAGE_SIDE = 1600
        private const val MAX_DECODE_PIXELS = 2_560_000L
    }

    private val handler = Handler(Looper.getMainLooper())
    private lateinit var face: AvatarSurface
    private lateinit var speechText: EditText
    private lateinit var stateText: TextView
    private val signal = TtsHologramSignal()
    private var voice: TextToSpeech? = null
    private var ready = false
    private var utteranceId: String? = null
    private var speaking = false
    private var resumed = false
    private var serial = 0L

    private val frame = object : Runnable {
        override fun run() {
            if (!speaking || !resumed || utteranceId == null) return
            face.setAudio(signal.level(SystemClock.elapsedRealtime()))
            handler.postDelayed(this, 50L)
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        window.statusBarColor = Color.rgb(4, 13, 30)
        window.navigationBarColor = Color.rgb(4, 13, 30)
        val density = resources.displayMetrics.density
        fun dp(n: Int): Int = (n * density + .5f).toInt()
        fun button(label: String, action: () -> Unit) = Button(this).apply {
            text = label
            isAllCaps = false
            setTextColor(Color.WHITE)
            setBackgroundColor(Color.rgb(17, 62, 103))
            setOnClickListener { action() }
        }
        val root = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(dp(14), dp(10), dp(14), dp(12))
            setBackgroundColor(Color.rgb(4, 13, 30))
        }
        root.addView(TextView(this).apply {
            text = "DEVICE AI  ·  AVATAR-LAB"
            textSize = 21f
            setTextColor(Color.rgb(122, 226, 255))
            gravity = Gravity.CENTER
        })
        root.addView(TextView(this).apply {
            text = "Kostenloser Offline-Test: Foto, Augen, Kopfneigung und sprachgesteuerte Mundbewegung. Die Kugel bleibt unser Markenzeichen."
            textSize = 12f
            setTextColor(Color.LTGRAY)
        })
        face = AvatarSurface()
        root.addView(face, LinearLayout.LayoutParams(-1, 0, 1f).apply { topMargin = dp(8) })
        val controls = LinearLayout(this).apply { orientation = LinearLayout.HORIZONTAL }
        controls.addView(button("Bild wählen") { choosePortrait() },
            LinearLayout.LayoutParams(0, dp(49), 1f))
        controls.addView(button("Blau / Hell") { face.toggleStyle() },
            LinearLayout.LayoutParams(0, dp(49), 1f).apply { marginStart = dp(6) })
        root.addView(controls)
        speechText = EditText(this).apply {
            setText("Hallo. Ich bin dein KI-Mitarbeiter. Wie kann ich dir helfen?")
            setTextColor(Color.WHITE)
            setHintTextColor(Color.GRAY)
            hint = "Text für die Sprachausgabe"
            textSize = 15f
            minLines = 2
            maxLines = 3
            setBackgroundColor(Color.rgb(14, 35, 65))
            setPadding(dp(10), dp(5), dp(10), dp(5))
        }
        root.addView(speechText, LinearLayout.LayoutParams(-1, -2).apply { topMargin = dp(8) })
        val speakControls = LinearLayout(this)
        speakControls.addView(button("Sprechen") { speak() }, LinearLayout.LayoutParams(0, dp(49), 1f))
        speakControls.addView(button("Stopp") { stopSpeech() },
            LinearLayout.LayoutParams(0, dp(49), 1f).apply { marginStart = dp(6) })
        root.addView(speakControls, LinearLayout.LayoutParams(-1, -2).apply { topMargin = dp(6) })
        stateText = TextView(this).apply {
            text = "Bild wählen · lokale Sprachengine wird geprüft"
            textSize = 12f
            setTextColor(Color.rgb(157, 204, 231))
        }
        root.addView(stateText, LinearLayout.LayoutParams(-1, -2).apply { topMargin = dp(6) })
        setContentView(root)
        getSharedPreferences(PREFS, MODE_PRIVATE).getString(PORTRAIT_URI, null)?.let {
            loadPortrait(Uri.parse(it))
        }
        voice = TextToSpeech(this) { status ->
            handler.post {
                if (isDestroyed) return@post
                ready = status == TextToSpeech.SUCCESS &&
                    (voice?.setLanguage(Locale.GERMAN) ?: TextToSpeech.LANG_NOT_SUPPORTED) >= TextToSpeech.LANG_AVAILABLE
                if (ready) installListener()
                stateText.text = if (ready) "Lokale Sprachausgabe bereit. Keine Cloud-Verbindung."
                    else "Keine lokale deutsche TTS-Stimme verfügbar. Sprachengine prüfen."
            }
        }
    }

    private fun choosePortrait() {
        val intent = Intent(Intent.ACTION_OPEN_DOCUMENT).apply {
            addCategory(Intent.CATEGORY_OPENABLE)
            type = "image/*"
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_GRANT_PERSISTABLE_URI_PERMISSION)
        }
        startActivityForResult(intent, PICK_PORTRAIT)
    }

    @Deprecated("Compatibility with Android 8+ pickers")
    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        super.onActivityResult(requestCode, resultCode, data)
        if (requestCode != PICK_PORTRAIT || resultCode != RESULT_OK) return
        val uri = data?.data ?: return
        try {
            contentResolver.takePersistableUriPermission(uri, Intent.FLAG_GRANT_READ_URI_PERMISSION)
            if (loadPortrait(uri)) {
                getSharedPreferences(PREFS, MODE_PRIVATE).edit().putString(PORTRAIT_URI, uri.toString()).apply()
            }
        } catch (error: Exception) {
            stateText.text = "Bild konnte nicht übernommen werden: " + (error.message ?: "Unbekannter Fehler")
        }
    }

    private fun loadPortrait(uri: Uri): Boolean {
        return try {
            val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
            contentResolver.openInputStream(uri)?.use { BitmapFactory.decodeStream(it, null, bounds) }
            if (bounds.outWidth <= 0 || bounds.outHeight <= 0) {
                stateText.text = "Bilddatei nicht lesbar."
                return false
            }
            var sample = 1
            while (max(bounds.outWidth, bounds.outHeight) / sample > MAX_IMAGE_SIDE ||
                (bounds.outWidth.toLong() / sample) * (bounds.outHeight / sample) > MAX_DECODE_PIXELS) {
                sample *= 2
            }
            val options = BitmapFactory.Options().apply { inSampleSize = sample }
            val bitmap = contentResolver.openInputStream(uri)?.use { BitmapFactory.decodeStream(it, null, options) }
            if (bitmap == null) {
                stateText.text = "Bilddatei nicht decodierbar."
                false
            } else {
                face.setPortrait(bitmap)
                stateText.text = "Bild lokal geladen. Zum Test auf Sprechen tippen."
                true
            }
        } catch (error: Exception) {
            stateText.text = "Bild nicht verfügbar: " + (error.message ?: "Fehler")
            false
        }
    }

    private fun installListener() {
        voice?.setOnUtteranceProgressListener(object : UtteranceProgressListener() {
            override fun onStart(id: String?) {
                if (id != utteranceId || id == null) return
                signal.anchor(id, 0, SystemClock.elapsedRealtime())
                runOnUiThread {
                    if (id != utteranceId || !resumed) return@runOnUiThread
                    speaking = true
                    face.setSpeaking(true)
                    handler.removeCallbacks(frame)
                    handler.post(frame)
                }
            }
            override fun onBeginSynthesis(id: String?, rate: Int, format: Int, channels: Int) {
                if (id != null && id == utteranceId) signal.begin(id, rate, format, channels)
            }
            override fun onAudioAvailable(id: String?, audio: ByteArray?) {
                if (id != null && id == utteranceId && audio != null) signal.append(id, audio)
            }
            override fun onRangeStart(id: String?, start: Int, end: Int, frame: Int) {
                if (id != null && id == utteranceId) {
                    signal.anchor(id, frame, SystemClock.elapsedRealtime())
                    runOnUiThread { if (id == utteranceId) face.onSpeechRange() }
                }
            }
            override fun onDone(id: String?) = finish(id)
            @Deprecated("Required for older synthesis implementations")
            override fun onError(id: String?) = finish(id)
            override fun onError(id: String?, errorCode: Int) = finish(id)
            override fun onStop(id: String?, interrupted: Boolean) = finish(id)
            private fun finish(id: String?) {
                runOnUiThread { if (id != null && id == utteranceId) stopSpeech() }
            }
        })
    }

    private fun speak() {
        if (!ready) {
            Toast.makeText(this, "Bitte lokale TTS-Stimme installieren oder aktivieren.", Toast.LENGTH_LONG).show()
            return
        }
        val text = speechText.text.toString().trim().take(800)
        if (text.isEmpty()) return
        stopSpeech()
        serial++
        val id = "avatar-lab-" + serial
        utteranceId = id
        signal.activate(id)
        if (voice?.speak(text, TextToSpeech.QUEUE_FLUSH, null, id) != TextToSpeech.SUCCESS) {
            stopSpeech()
            stateText.text = "Die Sprachengine konnte den Text nicht starten."
        }
    }

    private fun stopSpeech() {
        utteranceId = null
        speaking = false
        handler.removeCallbacks(frame)
        signal.stop()
        voice?.stop()
        if (::face.isInitialized) {
            face.setAudio(0f)
            face.setSpeaking(false)
        }
    }

    override fun onResume() {
        super.onResume()
        resumed = true
        if (::face.isInitialized) face.setActive(true)
    }
    override fun onPause() {
        stopSpeech()
        resumed = false
        if (::face.isInitialized) face.setActive(false)
        super.onPause()
    }
    override fun onDestroy() {
        handler.removeCallbacks(frame)
        voice?.shutdown()
        voice = null
        super.onDestroy()
    }

    private inner class AvatarSurface : View(this@ContinuumAvatarLabActivity) {
        private val paint = Paint(Paint.ANTI_ALIAS_FLAG or Paint.FILTER_BITMAP_FLAG)
        private var portrait: Bitmap? = null
        private var hologram = false
        private var active = false
        private var talking = false
        private var energy = 0f
        private var lastSpeechRangeMs = 0L

        fun setPortrait(value: Bitmap) {
            if (portrait !== value) portrait?.recycle()
            portrait = value
            invalidate()
        }
        fun toggleStyle() { hologram = !hologram; invalidate() }
        fun setActive(value: Boolean) { active = value; if (value) invalidate() }
        fun setSpeaking(value: Boolean) {
            talking = value
            if (!value) { energy = 0f; lastSpeechRangeMs = 0L }
            invalidate()
        }
        fun onSpeechRange() { lastSpeechRangeMs = SystemClock.uptimeMillis() }
        fun setAudio(value: Float) {
            val measured = if (value.isFinite()) value.coerceIn(0f, 1f) else 0f
            // Fallback for TTS engines that provide word ranges but no PCM chunks.
            // This is coarse word-level motion, NOT precise phoneme synchronization.
            val elapsed = (SystemClock.uptimeMillis() - lastSpeechRangeMs).coerceAtLeast(0L)
            val wordMotion = if (talking && measured == 0f && elapsed < 500L)
                (.10f + .18f * abs(sin(elapsed / 75f))) else 0f
            energy += (max(measured, wordMotion) - energy) * .4f
            invalidate()
        }
        override fun onDraw(canvas: Canvas) {
            super.onDraw(canvas)
            val w = width.toFloat()
            val h = height.toFloat()
            if (w <= 0f || h <= 0f) return
            canvas.drawColor(Color.rgb(3, 12, 30))
            val bmp = portrait
            if (bmp == null) {
                paint.color = Color.rgb(122, 226, 255)
                paint.textSize = 19f * resources.displayMetrics.scaledDensity
                canvas.drawText("Bitte Avatar-Bild auswählen", 18f, h / 2f, paint)
                return
            }
            val scale = min(w / bmp.width, h / bmp.height)
            val imgW = bmp.width * scale
            val imgH = bmp.height * scale
            val left = (w - imgW) * .5f
            val top = (h - imgH) * .5f
            val box = RectF(left, top, left + imgW, top + imgH)
            val t = SystemClock.uptimeMillis().toFloat()
            val sway = if (active) sin(t / 2300f) * .65f else 0f
            canvas.save()
            canvas.rotate(sway, left + imgW * .5f, top + imgH * .41f)
            paint.alpha = 255
            paint.color = Color.WHITE
            canvas.drawBitmap(bmp, null, box, paint)
            val eyeY = top + imgH * (if (hologram) .42f else .398f)
            val eyeShift = if (active) sin(t / 2700f) * imgW * .008f else 0f
            val blink = active && abs(sin(t / 3500f)) > .9985f
            for (eyeX in listOf(.397f, .609f)) {
                val x = left + imgW * eyeX + eyeShift
                paint.style = Paint.Style.STROKE
                paint.strokeWidth = max(1.3f, imgW * .003f)
                paint.color = Color.argb(if (blink) 160 else 95, 91, 225, 255)
                if (blink) {
                    canvas.drawLine(x - imgW * .035f, eyeY, x + imgW * .035f, eyeY, paint)
                } else {
                    canvas.drawCircle(x, eyeY, imgW * .011f, paint)
                }
            }
            // Image-space speech aperture: amplitude-reactive prototype, NOT phoneme rigging.
            // A full 3D facial rig needs independently editable lips and jaw geometry.
            val mouth = if (talking) max(0f, (energy - .025f) * 1.5f).coerceAtMost(1f) else 0f
            if (mouth > .035f) {
                val mx = left + imgW * .5f
                val my = top + imgH * (if (hologram) .631f else .604f)
                val rx = imgW * .082f
                val ry = imgH * (.002f + mouth * .023f)
                paint.style = Paint.Style.FILL
                paint.color = if (hologram) Color.rgb(4, 25, 62) else Color.rgb(11, 15, 28)
                canvas.drawOval(mx - rx, my - ry, mx + rx, my + ry, paint)
                paint.style = Paint.Style.STROKE
                paint.strokeWidth = max(1f, imgW * .004f)
                paint.color = if (hologram) Color.rgb(94, 230, 255) else Color.rgb(119, 186, 227)
                canvas.drawOval(mx - rx, my - ry, mx + rx, my + ry, paint)
            }
            canvas.restore()
            // Distinct branding – the original Continuum orb remains intact in the main UI.
            paint.style = Paint.Style.STROKE
            paint.strokeWidth = 2.5f
            paint.color = Color.rgb(89, 219, 255)
            canvas.drawCircle(w - 29f, 29f, 15f, paint)
            paint.style = Paint.Style.FILL
            paint.color = Color.rgb(108, 234, 255)
            canvas.drawCircle(w - 29f, 29f, 5f, paint)
            if (active) postInvalidateDelayed(66L)
        }
    }
}
