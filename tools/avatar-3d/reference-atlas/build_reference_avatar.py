"""Bake a supplied frontal portrait onto a real, morphable Continuum mesh.

Run with Blender 4.3 in background mode. This is surface authoring, not a
billboard: the original mesh, 21 morph displacements, joints and controls remain
unchanged. A new non-overlapping atlas is generated by splitting UV seam vertices
and copying every attribute and morph consistently. The unseen profile remains
an authored approximation, explicitly recorded in the output manifest.
"""
from pathlib import Path
import argparse
import copy
import hashlib
import json
import math
import struct
import sys

import bpy
import numpy as np


COMPONENTS = {5120: "i1", 5121: "u1", 5122: "<i2", 5123: "<u2", 5125: "<u4", 5126: "<f4"}
WIDTHS = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT2": 4, "MAT3": 9, "MAT4": 16}
MORPHS = ["SIL", "PP", "FF", "TH", "DD", "KK", "CH", "SS", "NN", "RR", "AA", "E", "I", "O", "U",
          "BlinkLeft", "BlinkRight", "BrowUp", "BrowDown", "Smile", "JawOpen"]
EXPECTED_SOURCE_SHA256 = "5f49eface4c828bb7f7564acee751e4d1f232a6e574b5038c6a564de69c9a4a3"
EXPECTED_REFERENCE_SHA256 = "0ca742ef92bb9db1bd012df7677594c37b58e77c40e4fc92a946e8e0fb886b1e"


def load_glb(path):
    raw = path.read_bytes()
    magic, version, length = struct.unpack_from("<III", raw)
    if (magic, version, length) != (0x46546C67, 2, len(raw)):
        raise ValueError("Expected a complete GLB version 2")
    size, kind = struct.unpack_from("<II", raw, 12)
    if kind != 0x4E4F534A:
        raise ValueError("Missing JSON chunk")
    doc = json.loads(raw[20:20 + size])
    binary_size, binary_type = struct.unpack_from("<II", raw, 20 + size)
    if binary_type != 0x004E4942:
        raise ValueError("Missing BIN chunk")
    binary = raw[28 + size:28 + size + binary_size]
    arrays = []
    for accessor in doc["accessors"]:
        if "sparse" in accessor:
            raise ValueError("This exact source contract has no sparse accessors")
        view = doc["bufferViews"][accessor["bufferView"]]
        dtype = np.dtype(COMPONENTS[accessor["componentType"]])
        width = WIDTHS[accessor["type"]]
        data = np.ndarray((accessor["count"], width), dtype=dtype, buffer=binary,
                          offset=view.get("byteOffset", 0) + accessor.get("byteOffset", 0),
                          strides=(view.get("byteStride", width * dtype.itemsize), dtype.itemsize)).copy()
        arrays.append(data)
    return raw, doc, arrays


def smoothstep(lo, hi, value):
    t = np.clip((value - lo) / (hi - lo), 0, 1)
    return t * t * (3 - 2 * t)


def monotone_interp(x, xp, fp):
    """Small monotone cubic Hermite interpolation; no SciPy dependency."""
    xp, fp = np.asarray(xp, float), np.asarray(fp, float)
    h = np.diff(xp)
    slopes = np.diff(fp) / h
    tangent = np.empty_like(xp)
    tangent[0], tangent[-1] = slopes[0], slopes[-1]
    for i in range(1, len(xp) - 1):
        if slopes[i - 1] * slopes[i] <= 0:
            tangent[i] = 0
        else:
            w1, w2 = 2 * h[i] + h[i - 1], h[i] + 2 * h[i - 1]
            tangent[i] = (w1 + w2) / (w1 / slopes[i - 1] + w2 / slopes[i])
    x = np.clip(x, xp[0], xp[-1])
    seg = np.clip(np.searchsorted(xp, x, side="right") - 1, 0, len(xp) - 2)
    t = (x - xp[seg]) / h[seg]
    return ((2 * t ** 3 - 3 * t ** 2 + 1) * fp[seg]
            + (t ** 3 - 2 * t ** 2 + t) * h[seg] * tangent[seg]
            + (-2 * t ** 3 + 3 * t ** 2) * fp[seg + 1]
            + (t ** 3 - t ** 2) * h[seg] * tangent[seg + 1])


def projection_uv(positions, width, height):
    y = positions[:, 1]
    source_y = monotone_interp(y,
        [0, .08, .14, .1778, .194, .21, .216, .2225, .230, .239, .250, .270, .2884144, .304, .330, .360, .3926764],
        [1448, 1365, 1195, 1070, 1000, 936, 884, 839, 801, 773, 725, 641, 551, 490, 359, 188, 45])
    x_scale = monotone_interp(y, [0, .14, .194, .23, .2884144, .34, .3926764],
                             [1950, 3700, 4500, 4700, 4740, 4450, 4450])
    x = 564 + positions[:, 0] * x_scale
    # Blender UVs have their origin at the lower left. The GLB writer flips V.
    return np.stack((x / width, 1 - source_y / height), axis=1).astype("<f4")


def continuation_uv(positions, width, height):
    """Reuse only the portrait's fine crown filaments on unspecified sides."""
    angle = np.arctan2(positions[:, 0], positions[:, 2] - .04)
    hue = np.clip(positions[:, 0] / .18 + .5, 0, 1)
    source_x = 410 + hue * 300 + 30 * np.sin(angle * 2.5)
    source_y = 195 + (1 - np.clip(positions[:, 1] / .4, 0, 1)) * 240
    return np.stack((source_x / width, 1 - source_y / height), axis=1).astype("<f4")


def math_node(nodes, links, op, a, b=None):
    node = nodes.new("ShaderNodeMath")
    node.operation = op
    for index, value in enumerate((a, b)):
        if value is None:
            continue
        if isinstance(value, (int, float)):
            node.inputs[index].default_value = value
        else:
            links.new(value, node.inputs[index])
    return node.outputs[0]


def authored_material(reference):
    mat = bpy.data.materials.new("ReferenceProjectionBake")
    mat.use_nodes = True
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    nodes.clear()
    output = nodes.new("ShaderNodeOutputMaterial")
    emission = nodes.new("ShaderNodeEmission")
    links.new(emission.outputs[0], output.inputs["Surface"])
    projection = nodes.new("ShaderNodeUVMap")
    projection.uv_map = "ProjectionUV"
    image_node = nodes.new("ShaderNodeTexImage")
    image_node.image = reference
    image_node.extension = "CLIP"
    image_node.interpolation = "Linear"
    links.new(projection.outputs[0], image_node.inputs["Vector"])
    confidence = nodes.new("ShaderNodeVertexColor")
    confidence.layer_name = "ReferenceWeight"
    factor = math_node(nodes, links, "MULTIPLY", confidence.outputs["Color"], image_node.outputs["Alpha"])

    # Unspecified side/back anatomy receives only the fine filament field from
    # a crown patch. Eyes, ears and lips never repeat onto the unseen surface.
    continuation = nodes.new("ShaderNodeUVMap")
    continuation.uv_map = "ContinuationUV"
    side_image = nodes.new("ShaderNodeTexImage")
    side_image.image = reference
    side_image.extension = "EXTEND"
    side_image.interpolation = "Linear"
    links.new(continuation.outputs[0], side_image.inputs["Vector"])
    multiply = nodes.new("ShaderNodeMixRGB")
    multiply.blend_type = "MULTIPLY"
    multiply.inputs[0].default_value = 1
    links.new(side_image.outputs["Color"], multiply.inputs[1])
    multiply.inputs[2].default_value = (.52, .52, .52, 1)
    mix = nodes.new("ShaderNodeMixRGB")
    mix.blend_type = "MIX"
    links.new(factor, mix.inputs[0])
    links.new(multiply.outputs[0], mix.inputs[1])
    links.new(image_node.outputs["Color"], mix.inputs[2])
    links.new(mix.outputs[0], emission.inputs["Color"])
    return mat


def resolve_uv_overlaps(positions, corners, uv, resolution=2048, known_faces=None):
    """Isolate conflicting triangles; do not relax the 1 mm overlap criterion.

    Smart projection can self-overlap concave oral/ear islands. Interior raster
    samples compare actual 3D positions and collect both sides of each conflict.
    Only those faces move to individually separated right-triangle atlas cells.
    """
    owners = np.full((resolution, resolution), -1, dtype=np.int32)
    positions_at_pixel = np.zeros((resolution, resolution, 3), dtype=np.float32)
    flagged = set(known_faces or [])
    for face_index in range(len(corners) // 3):
        first = face_index * 3
        points = uv[first:first + 3].astype(float) * (resolution - 1)
        xyz = positions[corners[first:first + 3]].astype(float)
        low = np.maximum(0, np.ceil(points.min(axis=0)).astype(int))
        high = np.minimum(resolution - 1, np.floor(points.max(axis=0)).astype(int))
        if np.any(low > high):
            continue
        yy, xx = np.mgrid[low[1]:high[1] + 1, low[0]:high[0] + 1]
        a, b, c = points
        denominator = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1])
        if abs(float(denominator)) < 1e-12:
            flagged.add(face_index)
            continue
        wa = ((b[1] - c[1]) * (xx - c[0]) + (c[0] - b[0]) * (yy - c[1])) / denominator
        wb = ((c[1] - a[1]) * (xx - c[0]) + (a[0] - c[0]) * (yy - c[1])) / denominator
        wc = 1 - wa - wb
        inside = (wa > 1e-4) & (wb > 1e-4) & (wc > 1e-4)
        values = wa[..., None] * xyz[0] + wb[..., None] * xyz[1] + wc[..., None] * xyz[2]
        previous = owners[low[1]:high[1] + 1, low[0]:high[0] + 1]
        previous_positions = positions_at_pixel[low[1]:high[1] + 1, low[0]:high[0] + 1]
        conflict = inside & (previous >= 0) & (np.linalg.norm(values - previous_positions, axis=2) > .001)
        if np.any(conflict):
            flagged.add(face_index)
            flagged.update(int(x) for x in np.unique(previous[conflict]))
        previous[inside] = face_index
        previous_positions[inside] = values[inside]
    if flagged:
        columns = math.ceil(math.sqrt(len(flagged)))
        cell = np.array([.09, .08], dtype=float) / columns
        for index, face_index in enumerate(sorted(flagged)):
            offset = np.array([.905, .915]) + cell * np.array([index % columns, index // columns])
            uv[face_index * 3:face_index * 3 + 3] = offset + cell * np.array([[.14, .14], [.86, .14], [.14, .86]])
    print("UV_ISOLATED", len(flagged), "triangles", flush=True)
    return uv, sorted(flagged)


def atlas_object(name, positions, indices, uv_projection, uv_continuation, confidence, mat, region):
    mesh = bpy.data.meshes.new(name + "BakeMesh")
    mesh.from_pydata(positions.tolist(), [], indices.reshape(-1, 3).tolist())
    mesh.update()
    obj = bpy.data.objects.new(name + "Bake", mesh)
    bpy.context.collection.objects.link(obj)
    for face in mesh.polygons:
        face.use_smooth = True
    mesh.materials.append(mat)
    project_uv = mesh.uv_layers.new(name="ProjectionUV")
    continue_uv = mesh.uv_layers.new(name="ContinuationUV")
    weights = mesh.color_attributes.new(name="ReferenceWeight", type="FLOAT_COLOR", domain="POINT")
    weight_data = np.ones((len(positions), 4), dtype=np.float32)
    weight_data[:, :3] = confidence[:, None]
    weights.data.foreach_set("color", weight_data.ravel())
    corner_vertex = np.array([loop.vertex_index for loop in mesh.loops], dtype=np.int64)
    project_uv.data.foreach_set("uv", uv_projection[corner_vertex].ravel())
    continue_uv.data.foreach_set("uv", uv_continuation[corner_vertex].ravel())
    atlas_uv = mesh.uv_layers.new(name="AtlasUV")
    mesh.uv_layers.active = atlas_uv
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.uv.smart_project(angle_limit=math.radians(58), island_margin=.007,
                            area_weight=.20, correct_aspect=True, scale_to_bounds=False)
    bpy.ops.object.mode_set(mode="OBJECT")
    uv = np.empty((len(mesh.loops), 2), dtype=np.float32)
    atlas_uv.data.foreach_get("uv", uv.ravel())
    x, y, width, height = region
    uv = uv * np.array([width, height], dtype=np.float32) + np.array([x, y], dtype=np.float32)
    isolated = []
    if name == "Face":
        _, coarse_conflicts = resolve_uv_overlaps(positions, corner_vertex, uv.copy(), resolution=1024)
        uv, isolated = resolve_uv_overlaps(positions, corner_vertex, uv, resolution=2048, known_faces=coarse_conflicts)
    atlas_uv.data.foreach_set("uv", uv.ravel())
    return obj, corner_vertex, uv, isolated


def duplicate_seams(doc, arrays, primitive, corner_vertex, uv):
    """Copy all original payloads; only duplicate a vertex when its UV differs."""
    table, source_vertices, new_uv, remapped = {}, [], [], []
    for vertex, coords in zip(corner_vertex, uv):
        key = (int(vertex), int(round(float(coords[0]) * 10 ** 8)), int(round(float(coords[1]) * 10 ** 8)))
        index = table.get(key)
        if index is None:
            index = len(source_vertices)
            table[key] = index
            source_vertices.append(int(vertex))
            new_uv.append([float(coords[0]), 1 - float(coords[1])])
        remapped.append(index)
    source_vertices = np.asarray(source_vertices, dtype=np.int64)
    old_count = len(arrays[primitive["attributes"]["POSITION"]])
    all_accessors = set(primitive["attributes"].values())
    for target in primitive.get("targets", []):
        all_accessors.update(target.values())
    # The inherited UV accessor is replaced by the new atlas.
    inherited_uv = primitive["attributes"].pop("TEXCOORD_0", None)
    if inherited_uv is not None:
        all_accessors.discard(inherited_uv)
    for accessor_index in all_accessors:
        original = arrays[accessor_index]
        if len(original) != old_count:
            raise ValueError("Unexpected vertex attribute count")
        arrays[accessor_index] = original[source_vertices].copy()
        doc["accessors"][accessor_index]["count"] = len(source_vertices)
    index_accessor = primitive["indices"]
    arrays[index_accessor] = np.asarray(remapped, dtype=arrays[index_accessor].dtype).reshape(-1, 1)
    doc["accessors"][index_accessor]["count"] = len(remapped)
    uv_accessor = len(arrays)
    arrays.append(np.asarray(new_uv, dtype="<f4"))
    doc["accessors"].append({"componentType": 5126, "count": len(new_uv), "type": "VEC2"})
    primitive["attributes"]["TEXCOORD_0"] = uv_accessor
    return {"oldVertexCount": old_count, "newVertexCount": len(source_vertices),
            "seamDuplicates": len(source_vertices) - old_count,
            "cornerCount": len(remapped), "sourceVertices": source_vertices.tolist()}


def pack_glb(doc, arrays, texture_bytes):
    binary = bytearray()
    views = []
    # Drop unreachable original UV arrays and material maps when repacking.
    used = set()
    element_accessors = set()
    vertex_accessors = set()
    for mesh in doc["meshes"]:
        for prim in mesh["primitives"]:
            used.update(prim["attributes"].values())
            vertex_accessors.update(prim["attributes"].values())
            if "indices" in prim:
                used.add(prim["indices"])
                element_accessors.add(prim["indices"])
            for target in prim.get("targets", []):
                used.update(target.values())
                vertex_accessors.update(target.values())
    for skin in doc.get("skins", []):
        if "inverseBindMatrices" in skin:
            used.add(skin["inverseBindMatrices"])
    for clip in doc.get("animations", []):
        for sampler in clip["samplers"]:
            used.update([sampler["input"], sampler["output"]])
    mapping = {old: new for new, old in enumerate(sorted(used))}
    accessors = []
    for old in sorted(used):
        array = np.ascontiguousarray(arrays[old])
        binary.extend(b"\0" * (-len(binary) % 4))
        view = {"buffer": 0, "byteOffset": len(binary), "byteLength": array.nbytes}
        if old in element_accessors:
            view["target"] = 34963
        elif old in vertex_accessors:
            view["target"] = 34962
        views.append(view)
        binary.extend(array.tobytes())
        accessor = copy.deepcopy(doc["accessors"][old])
        accessor["bufferView"] = len(views) - 1
        accessor.pop("byteOffset", None)
        if "min" in accessor:
            accessor["min"] = array.min(axis=0).tolist()
        if "max" in accessor:
            accessor["max"] = array.max(axis=0).tolist()
        accessors.append(accessor)
    for mesh in doc["meshes"]:
        for prim in mesh["primitives"]:
            prim["attributes"] = {name: mapping[idx] for name, idx in prim["attributes"].items()}
            if "indices" in prim:
                prim["indices"] = mapping[prim["indices"]]
            for target in prim.get("targets", []):
                for name, idx in list(target.items()):
                    target[name] = mapping[idx]
    for skin in doc.get("skins", []):
        if "inverseBindMatrices" in skin:
            skin["inverseBindMatrices"] = mapping[skin["inverseBindMatrices"]]
    for clip in doc.get("animations", []):
        for sampler in clip["samplers"]:
            sampler["input"] = mapping[sampler["input"]]
            sampler["output"] = mapping[sampler["output"]]
    binary.extend(b"\0" * (-len(binary) % 4))
    views.append({"buffer": 0, "byteOffset": len(binary), "byteLength": len(texture_bytes)})
    binary.extend(texture_bytes)
    doc["images"] = [{"bufferView": len(views) - 1, "mimeType": "image/png", "name": "ContinuumReferenceAtlas"}]
    doc["textures"] = [{"sampler": 0, "source": 0}]
    doc["samplers"] = [{"magFilter": 9729, "minFilter": 9987, "wrapS": 33071, "wrapT": 33071}]
    doc["accessors"], doc["bufferViews"] = accessors, views
    doc["buffers"] = [{"byteLength": len(binary)}]
    binary.extend(b"\0" * (-len(binary) % 4))
    encoded = json.dumps(doc, separators=(",", ":"), ensure_ascii=True).encode()
    encoded += b" " * (-len(encoded) % 4)
    return (struct.pack("<III", 0x46546C67, 2, 28 + len(encoded) + len(binary))
            + struct.pack("<II", len(encoded), 0x4E4F534A) + encoded
            + struct.pack("<II", len(binary), 0x004E4942) + binary)


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("source", type=Path)
    args.add_argument("reference", type=Path)
    args.add_argument("output", type=Path)
    args.add_argument("--size", type=int, default=2048)
    argv = sys.argv[sys.argv.index("--") + 1:]
    config = args.parse_args(argv)
    config.output.mkdir(parents=True, exist_ok=True)
    raw, doc, arrays = load_glb(config.source)
    if hashlib.sha256(raw).hexdigest() != EXPECTED_SOURCE_SHA256:
        raise ValueError("This calibrated derivation requires the documented 5f49 source GLB")
    if hashlib.sha256(config.reference.read_bytes()).hexdigest() != EXPECTED_REFERENCE_SHA256:
        raise ValueError("This calibrated derivation requires the documented generated frontal reference")
    source_doc = copy.deepcopy(doc)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    reference = bpy.data.images.load(str(config.reference.resolve()), check_existing=False)
    reference.alpha_mode = "STRAIGHT"
    width, height = reference.size
    if (width, height) != (1086, 1448):
        raise ValueError("Reference landmark calibration requires exactly 1086 x 1448 pixels")
    material = authored_material(reference)
    atlas = bpy.data.images.new("ContinuumReferenceAtlas", width=config.size, height=config.size, alpha=False)
    atlas.generated_color = (.001, .001, .004, 1)
    atlas.colorspace_settings.name = "sRGB"
    bake_target = material.node_tree.nodes.new("ShaderNodeTexImage")
    bake_target.image = atlas
    bake_target.name = "AtlasBakeTarget"
    material.node_tree.nodes.active = bake_target
    nodes = {node["name"]: node for node in doc["nodes"]}
    records = {}
    objects = []
    for name, region in [("Face", (.005, .005, .885, .99)),
                         ("IrisLeft", (.905, .505, .09, .40)),
                         ("IrisRight", (.905, .065, .09, .40))]:
        mesh = doc["meshes"][nodes[name]["mesh"]]
        if name == "Face" and mesh.get("extras", {}).get("targetNames") != MORPHS:
            raise ValueError("Unexpected morph contract")
        prim = mesh["primitives"][0]
        positions = arrays[prim["attributes"]["POSITION"]].copy()
        normals = arrays[prim["attributes"]["NORMAL"]]
        indices = arrays[prim["indices"]]
        if name.startswith("Iris"):
            side = "Left" if name.endswith("Left") else "Right"
            eye = nodes["Eye" + side]
            pivot = np.array(nodes["Neck"]["translation"]) + np.array(nodes["Head"]["translation"]) + np.array(eye["translation"])
            positions += pivot
            confidence = np.ones(len(positions), dtype=np.float32)
        else:
            # The frontal portrait only specifies visible front anatomy. Reduce
            # its influence around ears, back faces, and any hidden inner skin.
            confidence = smoothstep(-.12, .42, normals[:, 2])
            confidence *= smoothstep(.055, .115, positions[:, 2])
            # The portrait's drawn ears must not project onto the model's cheek,
            # temple or neck. Use the facial silhouette only in that height band.
            side_limit = monotone_interp(positions[:, 1],
                [0, .16, .194, .2225, .25, .27, .2884144, .305, .33, .36, .3926764],
                [.30, .055, .043, .051, .055, .056, .058, .066, .074, .072, .060])
            confidence *= 1 - smoothstep(side_limit - .009, side_limit + .004, np.abs(positions[:, 0]))
            # Broad shoulders use the same family of local filaments where the
            # portrait's transparent border contains no authored surface.
        uv_projection = projection_uv(positions, width, height)
        uv_continuation = continuation_uv(positions, width, height)
        obj, corner_vertex, uv, isolated = atlas_object(name, positions, indices, uv_projection, uv_continuation, confidence, material, region)
        objects.append(obj)
        records[name] = duplicate_seams(doc, arrays, prim, corner_vertex, uv)
        records[name]["isolatedUvTriangles"] = isolated
        print("ATLAS_OBJECT", name, len(positions), records[name]["newVertexCount"], flush=True)

    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.samples = 1
    scene.render.threads_mode = "FIXED"
    scene.render.threads = 2
    scene.render.bake.use_clear = True
    scene.render.bake.margin = 8
    scene.render.bake.margin_type = "EXTEND"
    for index, obj in enumerate(objects):
        bpy.ops.object.select_all(action="DESELECT")
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        obj.data.uv_layers.active = obj.data.uv_layers["AtlasUV"]
        material.node_tree.nodes.active = bake_target
        scene.render.bake.use_clear = index == 0
        bpy.ops.object.bake(type="EMIT")
        print("BAKED", obj.name, flush=True)
    atlas_path = config.output / "continuum-reference-atlas.png"
    atlas.filepath_raw = str(atlas_path.resolve())
    atlas.file_format = "PNG"
    atlas.save()

    materials = {mat["name"]: mat for mat in doc["materials"]}
    for name in ("DeepIndigoSkin", "CyanIris"):
        mat = materials[name]
        mat["pbrMetallicRoughness"] = {"baseColorFactor": [.16, .16, .16, 1], "baseColorTexture": {"index": 0},
                                      "metallicFactor": .08, "roughnessFactor": .52}
        mat["emissiveFactor"] = [1, 1, 1]
        mat["emissiveTexture"] = {"index": 0}
        mat["extensions"] = {"KHR_materials_emissive_strength": {"emissiveStrength": 1.35}}
        mat["alphaMode"] = "OPAQUE"
        mat["doubleSided"] = True
    materials["NaturalSclera"]["pbrMetallicRoughness"]["baseColorFactor"] = [.006, .022, .055, 1]
    materials["NaturalSclera"]["emissiveFactor"] = [.0015, .005, .015]
    materials["NaturalSclera"]["pbrMetallicRoughness"]["roughnessFactor"] = .18
    # Keep the old deformed filament meshes/targets for compatibility, but their
    # coarse cage must not obscure the reference's finer surface filaments.
    for name in ("VioletThreads", "CyanThreads"):
        mat = materials[name]
        mat["pbrMetallicRoughness"]["baseColorFactor"] = [0, 0, 0, 0]
        mat["emissiveFactor"] = [0, 0, 0]
        mat["alphaMode"], mat["alphaCutoff"] = "MASK", .5
